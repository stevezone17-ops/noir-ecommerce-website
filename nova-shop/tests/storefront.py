"""Browser regression against a disposable migrated DB with stock on product 1."""
import os,secrets
from playwright.sync_api import sync_playwright,expect
base=os.environ.get('NOIR_TEST_URL','http://localhost:3196')
with sync_playwright() as pw:
    browser=pw.chromium.launch(executable_path=os.environ.get('CHROMIUM_PATH','/usr/bin/chromium'),args=['--no-sandbox'])
    p=browser.new_page()
    records=p.request.get(base+'/api/catalog').json()
    assert set(range(1,9)) <= {r['id'] for r in records}
    p.goto(base+'/?edit=New#shop')
    catalog=p.locator('#shop')
    search=catalog.get_by_label('Search',exact=True)
    search.fill('linen')
    expect(catalog.locator('.tile')).to_have_count(1)
    assert catalog.locator('datalist option').first.get_attribute('value')=='Essential Linen Shirt'
    catalog.get_by_label('Max ₹').fill('1500')
    expect(catalog.get_by_text('No pieces match',exact=False)).to_be_visible()
    catalog.get_by_label('Max ₹').fill('')
    search.fill('')
    catalog.get_by_label('Category').select_option('Clothing')
    catalog.get_by_label('Size').select_option('Standard')
    catalog.get_by_label('Color').select_option('Original')
    catalog.get_by_label('Sort').select_option('low')
    expect(catalog.locator('h3').first).to_have_text('Relaxed Cotton Tee')
    if len(records)>8:
        p.goto(base+'/#shop')
        p.locator('#shop').get_by_role('button',name='Next').click()
        expect(p.locator('.pager')).to_contain_text('2 /')
    multi=next((r for r in records if len(r['variants'])>1 and r['variants'][1]['stock']>0),None)
    if multi:
        p.goto(base+'/products/'+str(multi['id']))
        p.get_by_label('Size and color').select_option('1')
        p.get_by_role('button',name='Add to bag',exact=True).click()
        expect(p.get_by_role('dialog')).to_contain_text(multi['variants'][1]['color'])
        key=str(multi['id'])+':'+str(multi['variants'][1]['id'])
        assert p.evaluate("key=>JSON.parse(localStorage.getItem('noir-cart'))[key]",key)==1
        p.get_by_role('dialog').get_by_role('button',name='Remove').click()
        p.keyboard.press('Escape')
    p.goto(base+'/products/1')
    expect(p).to_have_title('Essential Linen Shirt | NOIR')
    assert p.locator('meta[property="og:image"]').count()
    p.get_by_role('button',name='Show detail image').click()
    img=p.locator('.main-photo img')
    assert img.get_attribute('src').endswith('-detail.webp')
    p.wait_for_function("document.querySelector('.main-photo img').naturalWidth>0")
    p.get_by_role('button',name='Save to wishlist').click()
    p.get_by_label('Quantity').fill('2')
    p.get_by_role('button',name='Add to bag',exact=True).click()
    bag=p.get_by_role('dialog')
    expect(bag).to_contain_text('₹3,798')
    bag.get_by_role('button',name='Increase quantity').click()
    expect(bag).to_contain_text('₹5,697')
    p.keyboard.press('Escape')
    p.reload()
    p.get_by_role('button',name='Open shopping bag').click()
    expect(bag).to_contain_text('₹5,697')
    bag.get_by_role('button',name='Remove').click()
    expect(bag.get_by_text('Your bag is empty.',exact=False)).to_be_visible()
    p.keyboard.press('Escape')
    p.goto(base+'/?edit=Wishlist#shop')
    expect(p.locator('#shop .tile')).to_have_count(1)
    p.goto(base+'/')
    p.get_by_placeholder('Email address').fill(secrets.token_hex(8)+'@example.test')
    p.get_by_role('button',name='Subscribe').click()
    expect(p.get_by_text('You’re on the list.')).to_be_visible()
    for width in [320,768,1440]:
        p.set_viewport_size({'width':width,'height':900})
        for path in ['/','/products/1','/?edit=Wishlist#shop','/account']:
            p.goto(base+path)
            assert p.evaluate('document.documentElement.scrollWidth===innerWidth'),(width,path)
        if width==320:
            p.goto(base)
            p.get_by_role('button',name='Menu').click()
            p.get_by_role('navigation').get_by_role('link',name='Women',exact=True).click()
            expect(p.get_by_role('heading',name='Women’s collection')).to_be_visible()
    assert p.goto(base+'/products/99999999').status==404 or p.get_by_text('This page could not be found.').count()
    assert '/products/1' in p.request.get(base+'/sitemap.xml').text()
    assert '/admin' in p.request.get(base+'/robots.txt').text()
    browser.close()
    print('Database catalog, product details, search/suggestions, filters, sorting, bag, wishlist, newsletter, metadata and responsive pages passed.')
